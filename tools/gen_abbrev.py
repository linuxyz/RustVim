#!/usr/bin/env python3
"""Generate command abbreviations from the Vim index.txt documentation."""
import json
import re
from pathlib import Path

root = Path('/tmp/rvim-vim/vim-9.2.1338/runtime/doc/index.txt')
entries = {}
if root.exists():
    for line in root.read_text(errors='replace').splitlines():
        match = re.match(r'\|:([^|]+)\|\s+(:\S+)', line)
        if not match:
            continue
        spec = match.group(2).lstrip(':')
        parsed = re.match(r'^([A-Za-z]+)(?:\[([A-Za-z]*)\])?$', spec)
        if not parsed:
            continue
        prefix, rest = parsed.groups()
        full = prefix + (rest or '')
        least = prefix if rest is not None else full
        entries.setdefault(full, least)
lines = ['//! Generated by tools/gen_abbrev.py. Do not edit.', '', 'pub static COMMAND_ABBREVIATIONS: &[(&str, &str)] = &[']
for full, least in sorted(entries.items()):
    lines.append(f'    ({json.dumps(full)}, {json.dumps(least)}),')
lines.append('];')
Path('crates/rvim-editor/src/registry_abbrev.rs').write_text('\n'.join(lines) + '\n')
print('generated', len(entries))
