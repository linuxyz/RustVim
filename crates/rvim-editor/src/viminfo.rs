use std::io;
use std::path::{Path, PathBuf};

use rvim_edit::{RegisterContent, RegisterKind, RegisterName};
use rvim_types::{BufPos, VimString};

use crate::editor::Editor;

const HEADER: &str = "# This viminfo file was generated by RVim.\n# You may edit it if you're careful!\n\n# Viminfo version\n|1,4\n\n# Value of 'encoding' when this file was written\n*encoding=utf-8\n\n";

#[derive(Clone, Debug, Default)]
struct Parsed {
    commands: Vec<(String, u64)>,
    searches: Vec<(String, u64)>,
    registers: Vec<(RegisterName, RegisterKind, Vec<VimString>, u64)>,
    marks: Vec<(char, u32, u32, String, u64)>,
    globals: Vec<(String, rvim_viml::Value)>,
    global_exprs: Vec<(String, String)>,
    buffers: Vec<String>,
}

pub fn default_path(editor: &Editor) -> Option<PathBuf> {
    let configured = editor.options.get_string("viminfofile");
    if !configured.is_empty() && configured != "NONE" {
        return Some(PathBuf::from(configured));
    }
    let home = std::env::var_os("HOME")?;
    #[cfg(windows)]
    let name = "_viminfo";
    #[cfg(not(windows))]
    let name = ".viminfo";
    Some(PathBuf::from(home).join(name))
}

fn register_char(name: RegisterName) -> Option<char> {
    match name {
        RegisterName::Unnamed => Some('"'),
        RegisterName::Numbered(number) => char::from_digit(number as u32, 10),
        RegisterName::Small(letter) => Some(letter),
        RegisterName::LastInsert => Some('-'),
        RegisterName::LastCommand => Some(':'),
        RegisterName::LastSearch => Some('/'),
        _ => None,
    }
}

fn register_kind(kind: RegisterKind) -> &'static str {
    match kind {
        RegisterKind::Characterwise => "CHAR",
        RegisterKind::Linewise => "LINE",
        RegisterKind::Blockwise => "BLOCK",
    }
}

fn parse_kind(text: &str) -> RegisterKind {
    match text {
        "LINE" => RegisterKind::Linewise,
        "BLOCK" => RegisterKind::Blockwise,
        _ => RegisterKind::Characterwise,
    }
}

fn merge_history<'a>(
    current: impl Iterator<Item = &'a str>,
    existing: &[(String, u64)],
    now: u64,
) -> Vec<(String, u64)> {
    let mut entries: Vec<(String, u64)> = Vec::new();
    for item in current {
        if !item.is_empty() && !entries.iter().any(|entry| entry.0 == item) {
            entries.push((item.to_string(), now));
        }
    }
    for (item, time) in existing {
        if let Some(entry) = entries.iter_mut().find(|entry| entry.0 == *item) {
            entry.1 = entry.1.max(*time);
        } else if !item.is_empty() {
            entries.push((item.clone(), *time));
        }
    }
    entries.sort_by_key(|entry| std::cmp::Reverse(entry.1));
    entries
}

fn parse(text: &str) -> Parsed {
    let mut parsed = Parsed::default();
    let mut pending: Option<(RegisterName, RegisterKind, Vec<VimString>)> = None;
    for line in text.lines() {
        if let Some(rest) = line.strip_prefix("|H,C,") {
            let time = rest.trim().parse::<u64>().unwrap_or(0);
            if let Some(last) = parsed.commands.last_mut() {
                last.1 = time;
            }
            continue;
        }
        if let Some(rest) = line.strip_prefix("|H,S,") {
            let time = rest.trim().parse::<u64>().unwrap_or(0);
            if let Some(last) = parsed.searches.last_mut() {
                last.1 = time;
            }
            continue;
        }
        if let Some(rest) = line.strip_prefix("|M,") {
            let time = rest.trim().parse::<u64>().unwrap_or(0);
            if let Some(last) = parsed.marks.last_mut() {
                last.4 = time;
            }
            continue;
        }
        if let Some(rest) = line.strip_prefix("|R,") {
            let time = rest.trim().parse::<u64>().unwrap_or(0);
            if let Some((name, kind, lines)) = pending.take() {
                parsed.registers.push((name, kind, lines, time));
            } else if let Some(last) = parsed.registers.last_mut() {
                last.3 = time;
            }
            continue;
        }
        if line.is_empty()
            || line.starts_with('#')
            || line.starts_with('|')
            || line.starts_with('*')
        {
            continue;
        }
        if let Some(rest) = line.strip_prefix('\t') {
            if let Some((_, _, lines)) = pending.as_mut() {
                lines.push(VimString::from(rest.as_bytes().to_vec()));
            }
            continue;
        }
        if let Some((name, kind, lines)) = pending.take() {
            parsed.registers.push((name, kind, lines, 0));
        }
        if let Some(command) = line.strip_prefix(':') {
            parsed.commands.push((command.to_string(), 0));
        } else if let Some(search) = line.strip_prefix('/') {
            parsed.searches.push((search.to_string(), 0));
        } else if let Some(rest) = line.strip_prefix('"') {
            let mut parts = rest.split('\t');
            let Some(Some(name)) = parts.next().and_then(|text| text.chars().next().map(Some))
            else {
                continue;
            };
            let Some(name) = RegisterName::parse(name) else {
                continue;
            };
            let kind = parts
                .next()
                .map(parse_kind)
                .unwrap_or(RegisterKind::Characterwise);
            pending = Some((name, kind, Vec::new()));
        } else if let Some(path) = line.strip_prefix('%') {
            if !path.is_empty() {
                parsed.buffers.push(path.to_string());
            }
        } else if let Some(rest) = line.strip_prefix('!') {
            let Some((kind, rest)) = rest.split_once(':') else {
                continue;
            };
            let Some((name, value)) = rest.split_once('\t') else {
                continue;
            };
            if name.is_empty() {
                continue;
            }
            if kind == "V" {
                parsed
                    .global_exprs
                    .push((name.to_string(), value.to_string()));
                continue;
            }
            let value = match kind {
                "N" => value.parse::<i64>().ok().map(rvim_viml::Value::Number),
                "B" => value
                    .parse::<i64>()
                    .ok()
                    .map(|value| rvim_viml::Value::Bool(value != 0)),
                "S" => Some(rvim_viml::Value::string(value)),
                _ => None,
            };
            if let Some(value) = value {
                parsed.globals.push((name.to_string(), value));
            }
        } else if let Some(rest) = line.strip_prefix('\'') {
            let mut parts = rest.splitn(4, "  ");
            let Some(mark) = parts.next().and_then(|text| text.chars().next()) else {
                continue;
            };
            let lnum = parts
                .next()
                .and_then(|text| text.trim().parse::<u32>().ok())
                .unwrap_or(1);
            let col = parts
                .next()
                .and_then(|text| text.trim().parse::<u32>().ok())
                .unwrap_or(0);
            let Some(name) = parts.next() else {
                continue;
            };
            if !name.is_empty() {
                parsed.marks.push((mark, lnum, col, name.to_string(), 0));
            }
        }
    }
    if let Some((name, kind, lines)) = pending {
        parsed.registers.push((name, kind, lines, 0));
    }
    parsed
}

pub fn write(editor: &Editor, path: &Path) -> io::Result<()> {
    let existing = std::fs::read_to_string(path)
        .ok()
        .map(|text| parse(&text))
        .unwrap_or_default();

    let now = unix_now();
    let commands = merge_history(
        editor.command_history.iter().rev().map(String::as_str),
        &existing.commands,
        now,
    );
    let searches = merge_history(
        editor.search_history.iter().rev().map(String::as_str),
        &existing.searches,
        now,
    );

    let mut out = String::from(HEADER);
    out.push_str("# Command Line History (newest to oldest):\n");
    for (command, time) in &commands {
        out.push(':');
        out.push_str(command);
        out.push('\n');
        out.push_str(&format!("|H,C,{time}\n"));
    }
    out.push_str("\n# Search String History (newest to oldest):\n");
    for (search, time) in &searches {
        out.push('/');
        out.push_str(search);
        out.push('\n');
        out.push_str(&format!("|H,S,{time}\n"));
    }
    out.push_str("\n# Registers:\n");
    let now = unix_now();
    let mut entries: Vec<(char, RegisterContent, u64)> = Vec::new();
    for (name, content) in editor.registers.savable() {
        if let Some(ch) = register_char(name) {
            entries.push((ch, content.clone(), now));
        }
    }
    for (name, kind, lines, time) in &existing.registers {
        let Some(ch) = register_char(*name) else {
            continue;
        };
        if let Some(entry) = entries.iter_mut().find(|entry| entry.0 == ch) {
            if *time > now {
                entry.1 = RegisterContent::new(lines.clone(), *kind);
                entry.2 = *time;
            }
        } else {
            entries.push((ch, RegisterContent::new(lines.clone(), *kind), *time));
        }
    }
    for (ch, content, time) in entries {
        write_register(&mut out, ch, &content);
        out.push_str(&format!("|R,{time}\n"));
    }

    out.push_str("\n# Global variables:\n");
    let globals = editor.viml.globals();
    let globals = globals.borrow();
    for entry in &globals.entries {
        let name = String::from_utf8_lossy(entry.key.as_bytes()).into_owned();
        if name.contains('\t') || name.contains('\n') {
            continue;
        }
        match &entry.value {
            rvim_viml::Value::Number(value) => {
                out.push_str(&format!("!N:{name}\t{value}\n"));
            }
            rvim_viml::Value::Bool(value) => {
                out.push_str(&format!("!B:{name}\t{}\n", if *value { 1 } else { 0 }));
            }
            rvim_viml::Value::String(value) => {
                let text = String::from_utf8_lossy(value.as_bytes()).into_owned();
                if !text.contains('\t') && !text.contains('\n') {
                    out.push_str(&format!("!S:{name}\t{text}\n"));
                }
            }
            _ => {
                if let Some(expr) = value_expr(&entry.value) {
                    out.push_str(&format!("!V:{name}\t{expr}\n"));
                }
            }
        }
    }

    out.push_str("\n# Buffer list:\n");
    for id in editor.buffer_ids() {
        let Some(buffer) = editor.buffers.get(id) else {
            continue;
        };
        if !buffer.listed {
            continue;
        }
        let name = buffer.name_string();
        if !name.is_empty() {
            out.push('%');
            out.push_str(&name);
            out.push('\n');
        }
    }

    out.push_str("\n# File marks:\n");
    let now = unix_now();
    let mut marks: Vec<(char, u32, u32, String, u64)> = Vec::new();
    if let Some(buffer) = editor.current_buffer() {
        let name = buffer.name_string();
        if !name.is_empty() {
            for (mark, pos) in &buffer.marks {
                if *mark == '[' || *mark == ']' {
                    continue;
                }
                marks.push((*mark, pos.lnum, pos.col, name.clone(), now));
            }
        }
    }
    for mark in existing.marks {
        if let Some(entry) = marks
            .iter_mut()
            .find(|item| item.0 == mark.0 && item.3 == mark.3)
        {
            if mark.4 > now {
                *entry = mark;
            }
        } else {
            marks.push(mark);
        }
    }
    for (mark, lnum, col, name, time) in marks {
        out.push('\'');
        out.push(mark);
        out.push_str(&format!("  {lnum}  {col}  {name}\n"));
        out.push_str(&format!("|M,{time}\n"));
    }
    if let Some(parent) = path.parent() {
        if !parent.as_os_str().is_empty() {
            std::fs::create_dir_all(parent)?;
        }
    }
    rvim_platform::fs::write_file_atomic(path, out.as_bytes())
        .map_err(|error| io::Error::other(error.to_string()))
}

fn write_register(out: &mut String, ch: char, content: &RegisterContent) {
    out.push('"');
    out.push(ch);
    out.push('\t');
    out.push_str(register_kind(content.kind));
    out.push_str("\t0\n");
    for line in &content.lines {
        out.push('\t');
        out.push_str(&String::from_utf8_lossy(line.as_bytes()));
        out.push('\n');
    }
}

pub fn read(editor: &mut Editor, path: &Path) -> io::Result<()> {
    let text = std::fs::read_to_string(path)?;
    let parsed = parse(&text);
    for (command, _time) in parsed.commands.into_iter().rev() {
        push_unique_history(&mut editor.command_history, &command);
    }
    while editor.command_history.len() > 200 {
        editor.command_history.pop_front();
    }
    for (search, _time) in parsed.searches.into_iter().rev() {
        push_unique_history(&mut editor.search_history, &search);
    }
    while editor.search_history.len() > 200 {
        editor.search_history.pop_front();
    }
    for (name, kind, lines, _time) in parsed.registers {
        editor
            .registers
            .set(name, RegisterContent::new(lines, kind));
    }
    for path in parsed.buffers {
        let already = editor.buffer_ids().into_iter().any(|id| {
            editor
                .buffers
                .get(id)
                .is_some_and(|buffer| buffer.name_string() == path)
        });
        if !already {
            let _ = editor.add_unlisted_buffer(Some(std::path::Path::new(&path)));
        }
    }
    for (name, value) in parsed.globals {
        editor.viml.set_global(&name, value);
    }
    for (name, expr) in parsed.global_exprs {
        let source = format!("let g:{name} = {expr}\n");
        let _ = editor.source_viml(source.as_bytes(), "[viminfo]");
    }
    let current_name = editor
        .current_buffer()
        .map(|buffer| buffer.name_string())
        .unwrap_or_default();
    for (mark, lnum, col, name, _time) in parsed.marks {
        if !editor.oldfiles.iter().any(|item| item == &name) {
            editor.oldfiles.push(name.clone());
        }
        if current_name == name {
            if let Some(buffer) = editor.current_buffer_mut() {
                buffer.marks.insert(mark, BufPos::new(lnum, col));
            }
        }
    }
    let values = editor
        .oldfiles
        .iter()
        .map(|name| rvim_viml::Value::string(name.as_str()))
        .collect();
    editor
        .viml
        .set_vvar("oldfiles", rvim_viml::Value::list(values));
    Ok(())
}

fn push_unique_history(history: &mut std::collections::VecDeque<String>, value: &str) {
    if value.is_empty() || history.iter().any(|item| item == value) {
        return;
    }
    history.push_back(value.to_string());
}

fn value_expr(value: &rvim_viml::Value) -> Option<String> {
    match value {
        rvim_viml::Value::Number(value) => Some(value.to_string()),
        rvim_viml::Value::Float(value) => Some(format!("{value}")),
        rvim_viml::Value::Bool(value) => Some(if *value {
            "v:true".to_string()
        } else {
            "v:false".to_string()
        }),
        rvim_viml::Value::String(value) => Some(quote_vim_string(value.as_bytes())),
        rvim_viml::Value::List(list) => {
            let list = list.try_borrow().ok()?;
            let items: Option<Vec<String>> = list.items.iter().map(value_expr).collect();
            Some(format!("[{}]", items?.join(", ")))
        }
        rvim_viml::Value::Blob(blob) => {
            let bytes = blob.try_borrow().ok()?;
            let hex: String = bytes.iter().map(|byte| format!("{byte:02X}")).collect();
            Some(format!("0z{hex}"))
        }
        rvim_viml::Value::Special(value) => Some(value.to_string()),
        rvim_viml::Value::Funcref(function) => {
            let function = function.try_borrow().ok()?;
            if let Some(lambda) = &function.lambda {
                return Some(String::from_utf8_lossy(lambda.source.as_bytes()).into_owned());
            }
            if function.name.is_empty() {
                return None;
            }
            let name = quote_vim_string(function.name.as_bytes());
            if function.args.is_empty() {
                Some(format!("function({name})"))
            } else {
                let args: Option<Vec<String>> = function.args.iter().map(value_expr).collect();
                Some(format!("function({name}, [{}])", args?.join(", ")))
            }
        }
        rvim_viml::Value::Dict(dict) => {
            let dict = dict.try_borrow().ok()?;
            let mut entries = Vec::new();
            for entry in &dict.entries {
                entries.push(format!(
                    "{}: {}",
                    quote_vim_string(entry.key.as_bytes()),
                    value_expr(&entry.value)?
                ));
            }
            Some(format!("{{{}}}", entries.join(", ")))
        }
    }
}

fn quote_vim_string(bytes: &[u8]) -> String {
    let mut out = String::from("'");
    for byte in bytes {
        match byte {
            b'\'' => out.push_str("''"),
            b'\n' => out.push_str("\\n"),
            b'\t' => out.push_str("\\t"),
            b'\\' => out.push_str("\\\\"),
            _ => out.push(*byte as char),
        }
    }
    out.push('\'');
    out
}

fn unix_now() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_secs())
        .unwrap_or(0)
}
